// The desk card's place lists (frontend cardPlaces.generated.ts), built from the backend's own place data (plan C3, R8).
// packages/core/scripts/card-places.ts writes it; packages/core/test/card-places.test.ts fails when the committed frontend
// file no longer matches this output.

import { cardName } from "./compose";
import { PlaceBook, parsePlacesData } from "./places";
import { RAJASTHAN_DISTRICTS } from "../rajasthan";

interface RawPlaces {
  districts: { tag: string; hi: string[]; codes?: string[]; towns: { hi: string; tag: string }[] }[];
}

const uniq = (xs: string[]) => [...new Set(xs.map((x) => x.normalize("NFC").trim()).filter(Boolean))];

/** The generated module's full text, from rajasthan-places.json's parsed content */
export function cardPlacesModule(raw: RawPlaces): string {
  const book = new PlaceBook(parsePlacesData(raw as Parameters<typeof parsePlacesData>[0]));
  const districts = book.districts.map((d) => {
    const own = RAJASTHAN_DISTRICTS.find((x) => x.name === d.name);
    return { name: d.name, tag: d.tag, names: uniq([...book.spellingsOf(d.name), ...(own ? [own.hi, ...own.aliases] : [])]) };
  });
  // R8: a national place's card name keeps its spaces ("Uttar Pradesh"); its tag spelling stays among the names
  const nationals = book.nationals().map((d) => ({ name: cardName(d), names: uniq([cardName(d), ...book.spellingsOf(d.name)]) }));
  // Towns that are also everyday words, in any spelling (आंधी, आन्धी, बाप), are left out (R4)
  const towns = uniq(raw.districts.flatMap((d) => d.towns.map((t) => t.hi)).filter((t) => !PlaceBook.everydayWord(t))).sort();
  return `// GENERATED by backend packages/core/scripts/card-places.ts from rajasthan-places.json, rajasthan.ts and places.ts.
// Do not edit by hand: change the backend data and run the script again (plan C3, 23 Nov 2026).

/** Rajasthan's districts: English name, hashtag, and every spelling (English, Hindi, other names) */
export const CARD_DISTRICTS: readonly { name: string; tag: string; names: readonly string[] }[] = ${JSON.stringify(districts, null, 1)};

/** The national places the composer knows, with their spellings; \`name\` is the card's, with its spaces */
export const CARD_NATIONALS: readonly { name: string; names: readonly string[] }[] = ${JSON.stringify(nationals, null, 1)};

/** Rajasthan's towns in Hindi (everyday words left out) */
export const CARD_TOWNS: readonly string[] = ${JSON.stringify(towns)};
`;
}
