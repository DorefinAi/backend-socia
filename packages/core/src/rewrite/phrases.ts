// Phrase and synonym tables for the rule rewriter. A group is a set of phrases that can stand in for each
// other in news copy; a one-way pair only goes from the first to the second (the reverse would be wrong
// somewhere). Phrases are whole words: they never match inside a longer word, a name, a number or a
// quote (quotes and hashtags are masked before the swap).
//
// Hindi entries keep gender and case agreement: where two words differ in gender the entry carries the
// postposition or verb with it ("की बढ़ोतरी" / "का इजाफा"), and only oblique forms are listed where the
// direct form would change the verb ("हादसे में", not "हादसा"). No numbers, number words, months,
// weekdays, district or person names, or party names appear here.
//
// Legal, police and casualty words are never swapped, because a near-synonym there changes the facts:
// arrest / detain / nab, accused (आरोपी) / charged (अभियुक्त), investigation / inquiry / probe (जांच /
// पड़ताल), recovered / seized (बरामद / जब्त), murder / killing (हत्या / कत्ल), injured / killed, alleged
// / claimed, fake / forged (फर्जी / जाली), fraud / cheating, stay / ban (रोक / पाबंदी), appointed / posted,
// warning / alert (IMD levels), filed / registered, police / administration. Tests hold the list.
//
// English entries are lower case; a match in a sentence's middle that starts with a capital is taken for
// a name and left alone (headlines in Title Case are handled as such).

