/** Every phrase in the tables, for the size check */
export function phraseCount(): number {
  const groups = [...HI_GROUPS, ...EN_GROUPS, ...EN_HEADLINE_GROUPS];
  return groups.reduce((n, g) => n + g.length, 0) + (HI_ONE_WAY.length + EN_ONE_WAY.length) * 2;
}

/** Every word the tables can put into a text (tests: no word in a rewrite comes from nowhere) */
export function phraseWords(): Set<string> {
  const all = [...HI_GROUPS.flat(), ...EN_GROUPS.flat(), ...EN_HEADLINE_GROUPS.flat(), ...HI_ONE_WAY.flat(), ...EN_ONE_WAY.flat()];
  return new Set(all.flatMap((p) => p.toLowerCase().split(/[\s-]+/u)));
}
